<?php
/**
 * Regenerates data/asset-manifest.php from the files in THIS working copy.
 *
 * Run it locally (never on the server) after changing or upgrading any CSS,
 * JS or font asset, then deploy the manifest together with those files:
 *
 *     php tools/build-asset-manifest.php
 *
 * The manifest is what gd_asset() and tools/asset-check.php compare the
 * deployed files against, so a stale manifest means a useless deploy check.
 */
declare(strict_types=1);

if (PHP_SAPI !== 'cli') {
    http_response_code(403);
    exit("build-asset-manifest.php is a local build step; run it from the command line.\n");
}

$root  = dirname(__DIR__);
$paths = require __DIR__ . '/asset-list.php';

$manifest = [];
$missing  = [];
foreach ($paths as $rel) {
    $file = $root . '/' . $rel;
    if (!is_file($file)) { $missing[] = $rel; continue; }
    $manifest[$rel] = [
        'size'   => filesize($file),
        'sha256' => hash_file('sha256', $file),
    ];
    printf("  %-58s %8d bytes\n", $rel, $manifest[$rel]['size']);
}

if ($missing) {
    fwrite(STDERR, "\nERROR — listed in tools/asset-list.php but not on disk:\n  - "
        . implode("\n  - ", $missing) . "\nManifest NOT written.\n");
    exit(1);
}

$out = "<?php\n"
     . "/**\n"
     . " * AUTO-GENERATED by tools/build-asset-manifest.php — do not edit by hand.\n"
     . " * Generated: " . gmdate('Y-m-d H:i:s') . " UTC\n"
     . " *\n"
     . " * Expected size + SHA-256 of every asset that must land in production\n"
     . " * byte-for-byte. gd_asset() checks sizes on each request; \n"
     . " * tools/asset-check.php verifies the hashes on demand.\n"
     . " */\n"
     . "return " . var_export($manifest, true) . ";\n";

$dest = $root . '/data/asset-manifest.php';
if (file_put_contents($dest, $out) === false) {
    fwrite(STDERR, "ERROR — could not write {$dest}\n");
    exit(1);
}

echo "\nWrote data/asset-manifest.php (" . count($manifest) . " assets).\n";
echo "Deploy it alongside the files above, then run tools/asset-check.php on the server.\n";
